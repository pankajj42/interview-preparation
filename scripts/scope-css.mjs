// Re-scopes the two original guide stylesheets under .dp-scope / .sd-scope so their (unchanged) rules can live in the
// new app without leaking. Theme selectors are mapped to the app's colour-scheme attribute; "system" is resolved in JS.
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const root = path.resolve(import.meta.dirname, '..');

function scopeCss(css, scope, label) {
  const dark = `[data-mui-color-scheme="dark"] ${scope}`;
  const mapSel = (sel) => {
    sel = sel.trim();
    if (/^:root:not\(/.test(sel)) return null;
    let m = sel.match(/^:root\[data-theme="(light|dark|system)"\](.*)$/);
    if (m) return m[1] === 'system' ? null : (m[1] === 'dark' ? dark : scope) + m[2];
    if (/^(html|body)$/.test(sel)) return scope;
    m = sel.match(/^:root(.*)$/);
    if (m) return scope + m[1];
    return `${scope} ${sel}`;
  };
  const root_ = postcss.parse(css);
  root_.walkAtRules((at) => {
    if (at.name === 'media' && /prefers-color-scheme\s*:\s*dark/.test(at.params)) at.remove();
  });
  root_.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    const original = rule.selector.trim();
    const sels = rule.selectors.map(mapSel).filter(Boolean);
    if (!sels.length) { rule.remove(); return; }
    if (original === 'html') { rule.remove(); return; }
    if (original === 'body') {
      rule.walkDecls((d) => {
        if (/^(background|margin|min-height)/.test(d.prop)) d.remove();
        if (d.prop === 'font' && /Inter/.test(d.value)) d.value = '15px/1.65 var(--font-sans)';
        if (d.prop === 'font-family') d.value = 'var(--font-sans)';
      });
    }
    rule.selectors = sels;
  });
  root_.walkAtRules((at) => { if (at.nodes && at.nodes.length === 0) at.remove(); });
  return `/* ${label}: original guide CSS, re-scoped under ${scope} (generated by scripts/scope-css.mjs) */\n${root_.toString()}\n`;
}

fs.mkdirSync(path.join(root, 'src/styles'), { recursive: true });
for (const [file, scope] of [['dp', '.dp-scope'], ['sd', '.sd-scope']]) {
  const css = fs.readFileSync(path.join(root, `scripts/source/${file}.css`), 'utf8');
  const out = scopeCss(css, scope, file);
  fs.writeFileSync(path.join(root, `src/styles/${file}-scope.css`), out);
  console.log(file, css.length, '->', out.length, 'bytes');
}
